// The token radar's model: one snapshot of the protocol universe in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and may add
// pre-token protocols below the watchlist floor: the early rows the radar exists to find. A protocol is
// pre-token when its index entry records no token (no market cap, no CoinGecko id, no symbol); the
// snapshot's live-token protocols are kept apart and shown as the market's own values, never mixed into
// the ranked board.
//
// Implied value is a comparable-token valuation scaled by a launch-readiness factor, all from the
// snapshot's own figures:
//
//   fdv           = tvl_usd x fdv_multiple            a protocol at TVL T that issues a token trades at a
//                                                     multiple of T; the multiple decays with age, since a
//                                                     token that took years to arrive has less upside left
//   readiness     = base + w_size x size + w_momentum x momentum + w_persist x persistence + w_breadth x breadth
//                   each factor 0..1, from TVL, 7-day growth, days run with no token, and chain count
//   implied       = clamp(round(fdv x readiness), 1, IMPLIED_CAP)
//
// No protocol name is ever special-cased: the same function scores every row. The constants below are the
// dashboard's stated model and may be changed in one place.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The model's constants, as the dashboard states them. */
export interface ModelConstants {
  /** A protocol's token tends to list at this multiple of its TVL, before readiness. */
  fdv_multiple: number;
  /** The age (days) at which the comparable multiple has decayed to `fdv_floor` of itself. */
  fdv_decay_days: number;
  /** The fraction of the multiple a very old protocol still carries. */
  fdv_floor: number;
  /** Readiness is a weighted blend of these four 0..1 factors plus a base. */
  readiness_base: number;
  weight_size: number;
  weight_momentum: number;
  weight_persistence: number;
  weight_breadth: number;
  /** TVL that scores full marks on the size factor, and the floor where it starts (log scale). */
  size_full_usd: number;
  size_floor_usd: number;
  /** 7-day growth (per cent) that scores full and the worst that scores zero, before clamping. */
  momentum_full_pct: number;
  momentum_floor_pct: number;
  /** Days run with no token that scores full marks on persistence. */
  persistence_full_days: number;
  /** Chain count that scores full marks on breadth. */
  breadth_full_chains: number;
  unknown_age_days: number;
}

export const MODEL: ModelConstants = {
  fdv_multiple: 0.45,
  fdv_decay_days: 1095,
  fdv_floor: 0.4,
  readiness_base: 0.25,
  weight_size: 0.20,
  weight_momentum: 0.35,
  weight_persistence: 0.15,
  weight_breadth: 0.05,
  size_full_usd: 500_000_000,
  size_floor_usd: 10_000_000,
  momentum_full_pct: 35,
  momentum_floor_pct: -25,
  persistence_full_days: 540,
  breadth_full_chains: 4,
  unknown_age_days: 365,
};

/** The model's version label: the dashboard names it and the rules quote it. */
